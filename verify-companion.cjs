const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
for(const file of ['miku-companion.png','ganbatte.mp3','yatta.mp3','daijoubu.mp3','sugoi.mp3','otsukare.mp3'])assert(fs.statSync('assets/'+file).size>1000);
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.addInitScript(()=>{
      const OriginalAudio=window.Audio;window.companionTestAudio=[];
      window.Audio=function(...args){const audio=new OriginalAudio(...args);window.companionTestAudio.push(audio);return audio;};
    });
    await page.goto('http://127.0.0.1:4173/?subject=image');
    const panel=page.locator('.study-companion'),voice=page.locator('#companion-voice');
    await panel.waitFor({state:'visible'});
    assert.equal(await panel.getAttribute('data-mood'),'welcome');
    assert(await page.evaluate(()=>companionTestAudio[0].paused));
    await page.locator('[data-image-field="lengthRule"]').selectOption('all');
    await page.locator('[data-image-answer="1"]').click();
    await panel.waitFor({state:'visible'});
    assert.equal(await panel.getAttribute('data-mood'),'correct');
    assert.equal(await panel.getAttribute('data-cue'),'correct');
    await page.waitForFunction(()=>companionTestAudio[0].readyState>=2&&!companionTestAudio[0].paused);
    assert((await page.evaluate(()=>companionTestAudio[0].duration))>0);
    assert((await page.locator('.companion-phrase').innerText()).includes('Yatta'));
    await page.keyboard.press('Escape');
    assert(await panel.isVisible());
    assert(await panel.locator('.companion-bubble').isHidden());
    await page.evaluate(()=>studyCompanion.react({correct:true,source:'image'}));
    await panel.waitFor({state:'visible'});
    await page.getByRole('button',{name:'Ẩn lời nhắn',exact:true}).click();
    assert(await panel.isVisible());
    assert(await panel.locator('.companion-bubble').isHidden());
    assert(await page.evaluate(()=>companionTestAudio[0].paused));
    await page.locator('[data-image-field="question"]').selectOption('2');
    await page.locator('[data-image-answer="0"]').click();
    await panel.waitFor({state:'visible'});
    assert.equal(await panel.getAttribute('data-mood'),'wrong');
    await voice.click();assert.equal(await voice.getAttribute('aria-pressed'),'false');
    await voice.click();
    await page.waitForFunction(()=>companionTestAudio[0].currentSrc.endsWith('/daijoubu.mp3')&&companionTestAudio[0].readyState>=2);
    await voice.click();
    await page.reload();
    await page.locator('#companion-toggle').waitFor();
    await page.evaluate(()=>studyCompanion.react({kind:'welcome'}));
    await panel.waitFor({state:'visible'});
    assert.equal(await voice.getAttribute('aria-pressed'),'false');
    const progress=await page.evaluate(()=>localStorage.getItem('image-processing-quiz-v1'));
    await page.locator('#companion-toggle').click();
    assert(await panel.isHidden());
    await page.evaluate(()=>studyCompanion.react({correct:true}));
    assert(await panel.isHidden());
    await page.reload();
    await page.locator('#companion-toggle').waitFor();
    assert.equal(await page.locator('#companion-toggle').getAttribute('aria-pressed'),'false');
    await page.locator('#companion-toggle').click();
    await page.evaluate(()=>{for(let i=0;i<3;i++)studyCompanion.react({correct:true,source:'test'});});
    await page.waitForFunction(()=>document.querySelector('.companion-speech').textContent.includes('3 câu đúng'));
    assert.equal(await panel.getAttribute('data-cue'),'streak');
    await page.evaluate(()=>studyCompanion.react({kind:'complete'}));
    await page.waitForFunction(()=>document.querySelector('.study-companion').dataset.cue==='complete');
    assert.equal(await page.evaluate(()=>localStorage.getItem('image-processing-quiz-v1')),progress);
    await page.emulateMedia({reducedMotion:'reduce'});
    assert.equal(await panel.evaluate(el=>getComputedStyle(el).animationName),'none');
    fs.mkdirSync('.test-artifacts',{recursive:true});
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:'.test-artifacts/companion-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>studyCompanion.react({correct:false,source:'image'}));
    await panel.waitFor({state:'visible'});
    assert(await page.evaluate(()=>document.querySelector('main').contains(document.querySelector('.study-companion'))));
    assert(await page.evaluate(()=>document.querySelector('.study-companion').getBoundingClientRect().top>=document.querySelector('.image-feedback').getBoundingClientRect().bottom));
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:'.test-artifacts/companion-mobile.png',fullPage:true});
    await page.setViewportSize({width:1024,height:600});
    assert.equal(await panel.evaluate(el=>getComputedStyle(el).position),'relative');
    const durations=await page.evaluate(()=>Promise.all(['ganbatte','yatta','daijoubu','sugoi','otsukare'].map(name=>new Promise((resolve,reject)=>{
      const audio=new Audio('assets/'+name+'.mp3');audio.preload='metadata';
      audio.onloadedmetadata=()=>resolve(audio.duration);audio.onerror=()=>reject(new Error(name+' failed to decode'));
    }))));
    assert(durations.every(duration=>duration>0&&duration<10));
    assert.deepEqual(errors,[]);
    console.log('PASS: correct/wrong reactions, playable audio, mute and disable persistence, streak/completion, unchanged progress, inline mobile placement, reduced motion and all 5 audio clips');
  } finally {await browser.close();}
})();
